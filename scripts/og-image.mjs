// Regenerates src/web/seo/og-image-data.ts: the 1200×630 link preview (Open Graph / X card) of the
// public pages, drawn as HTML in the site's palette and fonts and screenshotted with Playwright.
// Usage: NODE_PATH=$(npm root -g) node scripts/og-image.mjs   (then `npm run format`).
// Texts are English on purpose: one image serves every language and the audience is international.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
// Playwright is not a project dependency: use a global install (NODE_PATH=$(npm root -g)) or npx.
const { chromium } = require('playwright');
const font = (spec) => readFileSync(require.resolve(spec)).toString('base64');
const ONEST = font('@fontsource-variable/onest/files/onest-latin-wght-normal.woff2');
const MONO = font('@fontsource-variable/jetbrains-mono/files/jetbrains-mono-latin-wght-normal.woff2');

const chips = ['gmail:work', 'gmail:personal', 'slack:team', 'notion:wiki', 'github:company'];

const html = `<!doctype html><html><head><meta charset="utf-8"><style>
@font-face{font-family:Onest;src:url(data:font/woff2;base64,${ONEST}) format("woff2");font-weight:100 900}
@font-face{font-family:Mono;src:url(data:font/woff2;base64,${MONO}) format("woff2");font-weight:100 800}
*{box-sizing:border-box;margin:0}
body{width:1200px;height:630px;background:#f6f6f4;font-family:Onest,sans-serif;color:#1c1c1e;overflow:hidden;position:relative}
.wrap{position:absolute;inset:0;padding:72px 80px;display:flex;flex-direction:column}
.brand{display:flex;align-items:center;gap:18px;font-size:40px;font-weight:650;letter-spacing:-.02em}
.brand svg{width:64px;height:64px}
h1{margin-top:56px;font-size:76px;line-height:1.02;letter-spacing:-.045em;font-weight:700;max-width:900px}
h1 span{background:#ff6b1a;padding:0 14px;border-radius:14px;box-decoration-break:clone}
p{margin-top:26px;font-size:30px;color:#5f5f66;letter-spacing:-.01em}
.chips{margin-top:auto;display:flex;gap:12px;flex-wrap:wrap}
.chip{font:500 22px Mono,monospace;padding:10px 16px;border:2px solid #e4e4e0;background:#fff;border-radius:999px;color:#1c1c1e}
.chip b{color:#c2410c;font-weight:600}
.url{position:absolute;right:80px;top:84px;font:500 26px Mono,monospace;color:#5f5f66}
.ring{position:absolute;right:-140px;bottom:-200px;width:620px;height:620px;border-radius:50%;border:56px solid #ff6b1a;opacity:.12}
</style></head><body>
<div class="ring"></div>
<div class="wrap">
  <div class="brand"><svg viewBox="0 0 32 32"><rect width="32" height="32" rx="8" fill="#1c1c1e"/><path d="M16 7a9 9 0 1 1-9 9" fill="none" stroke="#ff6b1a" stroke-width="2.8" stroke-linecap="round"/><circle cx="16" cy="16" r="3.4" fill="#ff6b1a"/><circle cx="7" cy="9.6" r="2" fill="#ff6b1a"/></svg>Manyplug</div>
  <h1>All your accounts<br><span>in any AI assistant.</span></h1>
  <p>One MCP address for Claude, ChatGPT, Cursor and more.</p>
  <div class="chips">${chips
    .map((c) => {
      const [s, a] = c.split(':');
      return `<span class="chip">${s}:<b>${a}</b></span>`;
    })
    .join('')}</div>
</div>
<div class="url">manyplug.com</div>
</body></html>`;

const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: 1200, height: 630 }, deviceScaleFactor: 1 });
  await page.setContent(html, { waitUntil: 'load' });
  await page.evaluate(() => document.fonts.ready);
  const png = await page.screenshot({ type: 'png' });
  writeFileSync(
    new URL('../src/web/seo/og-image-data.ts', import.meta.url),
    `// Generated by scripts/og-image.mjs — do not edit by hand.\n/** The 1200×630 PNG link preview, base64. */\nexport const OG_IMAGE_BASE64 =\n  '${png.toString('base64')}';\n`,
  );
  console.log(`og image: ${png.length} bytes`);
} finally {
  await browser.close();
}
