// Regenerates src/web/brand-icons.ts from the `simple-icons` package (CC0 SVG paths of brand marks).
// Only the brands the website shows are copied, so the runtime does not load thousands of icons.
// Usage: node scripts/brand-icons.mjs   (then `npm run format`)
import { writeFileSync } from 'node:fs';
import * as icons from 'simple-icons';

const SLUGS = [
  'gmail',
  'googlecalendar',
  'googledrive',
  'googlesheets',
  'googlegemini',
  'notion',
  'github',
  'gitlab',
  'todoist',
  'stripe',
  'telegram',
  'whatsapp',
  'claude',
  'anthropic',
  'cursor',
  'windsurf',
  'modelcontextprotocol',
  'jira',
  'linear',
  'trello',
  'hubspot',
  'shopify',
  'airtable',
  'discord',
  'zoom',
  'dropbox',
  'asana',
  'clickup',
  'figma',
  'zapier',
  'n8n',
  'supabase',
  'postgresql',
  'youtube',
  'x',
  'perplexity',
  'protonmail',
  'icloud',
  'confluence',
  'miro',
  'calendly',
  'intercom',
  'zendesk',
  'sentry',
  'typeform',
  'wordpress',
  'mailchimp',
];

const out = {};
for (const slug of SLUGS) {
  const icon = Object.values(icons).find((i) => i && i.slug === slug);
  if (!icon) throw new Error(`simple-icons has no "${slug}"`);
  out[slug] = { title: icon.title, hex: `#${icon.hex}`, path: icon.path };
}

const body = `// Generated by scripts/brand-icons.mjs from simple-icons (CC0). Do not edit by hand.
// Brand marks belong to their owners; they are shown only to say which services Manyplug connects.

export interface BrandIcon {
  title: string;
  /** Brand color. */
  hex: string;
  /** SVG path on a 24×24 view box. */
  path: string;
}

export const BRAND_ICONS: Record<string, BrandIcon> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(new URL('../src/web/brand-icons.ts', import.meta.url), body);
console.log(`wrote ${SLUGS.length} icons`);
