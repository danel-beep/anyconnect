// Regenerates src/web/brand-icons.ts from the `simple-icons` package (CC0 SVG paths of brand marks).
// Only the brands the website shows are copied, so the runtime does not load thousands of icons.
// Marks the current simple-icons release lacks (Slack, Outlook, Twilio…) come from
// scripts/brand-icons-extra.json, each with its open source noted there.
// Usage: node scripts/brand-icons.mjs   (then `npm run format`)
import { readFileSync, writeFileSync } from 'node:fs';
import * as icons from 'simple-icons';

const SLUGS = [
  'gmail',
  'googlecalendar',
  'googledrive',
  'googlesheets',
  'googlegemini',
  'notion',
  'github',
  'gitlab',
  'todoist',
  'stripe',
  'telegram',
  'whatsapp',
  'claude',
  'anthropic',
  'cursor',
  'windsurf',
  'modelcontextprotocol',
  'jira',
  'linear',
  'trello',
  'hubspot',
  'shopify',
  'airtable',
  'discord',
  // Not 'zoom': simple-icons has only Zoom's wordmark, unreadable in a logo tile (a letter mark is in brand-monograms.ts).
  'dropbox',
  'asana',
  'clickup',
  'figma',
  'zapier',
  'n8n',
  'supabase',
  'postgresql',
  'youtube',
  'x',
  'perplexity',
  'protonmail',
  'icloud',
  'confluence',
  'miro',
  'calendly',
  'intercom',
  'zendesk',
  'sentry',
  'wordpress',
  'mailchimp',
  'vercel',
  'cloudflare',
  'bitbucket',
  'brevo',
  'webflow',
  'pagerduty',
  'netlify',
  // Toggl Track's power-button mark ('toggl' is the company wordmark, unreadable in a logo tile).
  'toggltrack',
  // Cal.com and Typeform are wordmarks here; their app icons are in brand-icons-extra.json.
];

const out = {};
for (const slug of SLUGS) {
  const icon = Object.values(icons).find((i) => i && i.slug === slug);
  if (!icon) throw new Error(`simple-icons has no "${slug}"`);
  out[slug] = { title: icon.title, hex: `#${icon.hex}`, path: icon.path };
}

const { _about, ...extra } = JSON.parse(
  readFileSync(new URL('./brand-icons-extra.json', import.meta.url), 'utf8'),
);
for (const [slug, { title, hex, path, evenodd }] of Object.entries(extra)) {
  if (out[slug]) throw new Error(`"${slug}" is in both simple-icons and brand-icons-extra.json`);
  if (!/^#[0-9A-Fa-f]{6}$/.test(hex) || !path) throw new Error(`brand-icons-extra.json: bad "${slug}"`);
  out[slug] = { title, hex, path, ...(evenodd ? { evenodd: true } : {}) };
}

const body = `// Generated by scripts/brand-icons.mjs from simple-icons (CC0) and scripts/brand-icons-extra.json. Do not edit by hand.
// Brand marks belong to their owners; they are shown only to say which services Manyplug connects.

export interface BrandIcon {
  title: string;
  /** Brand color. */
  hex: string;
  /** SVG path on a 24×24 view box. */
  path: string;
  /** Fill with the even-odd rule (the path has cut-out shapes). */
  evenodd?: boolean;
}

export const BRAND_ICONS: Record<string, BrandIcon> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(new URL('../src/web/brand-icons.ts', import.meta.url), body);
console.log(`wrote ${Object.keys(out).length} icons`);
